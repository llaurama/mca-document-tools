// Bundles each tool's ES modules into one classic script so the site works when opened from
// file://, where browsers refuse to load module scripts. No dependencies: modules are
// concatenated in import order inside one function scope, so every top-level name must be
// unique across a tool's modules, and imports may not rename (`as`).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const JS_DIR = resolve(ROOT, 'site/assets/js');
export const TOOLS = ['bank-statements', 'mca-applications'];
export const bundlePath = tool => resolve(JS_DIR, `${tool}.bundle.js`);

const IMPORT = /^import\s*\{([^}]*)\}\s*from\s*'([^']+)';[ \t]*\n/gm;
const EXPORT_LIST = /^export\s*\{[^}]*\};?[ \t]*\n/gm;
const EXPORT_PREFIX = /^export (?=(?:async )?(?:function|const|let|var|class)\b)/gm;
const DECLARATION = /^(?:async\s+)?(?:function\*?|const|let|var|class)\s+(?:([A-Za-z_$][\w$]*)|\{([^}]*)\})/gm;

function readModules(entry) {
  const modules = [];
  const done = new Set();
  const visiting = new Set();
  const visit = file => {
    if (done.has(file)) return;
    if (visiting.has(file)) throw new Error(`Import cycle through ${relative(JS_DIR, file)}`);
    visiting.add(file);
    const source = readFileSync(file, 'utf8');
    for (const [, , specifier] of source.matchAll(IMPORT)) visit(resolve(dirname(file), specifier));
    visiting.delete(file);
    done.add(file);
    modules.push({ name: relative(JS_DIR, file), source });
  };
  visit(entry);
  return modules;
}

// `modules` must already be in dependency order.
export function bundle(modules, entryName) {
  const owners = new Map();
  const bodies = modules.map(({ name, source }) => {
    for (const [, names] of source.matchAll(IMPORT)) {
      if (/\bas\b/.test(names)) throw new Error(`${name}: renamed imports are not supported`);
    }
    const body = source.replace(IMPORT, '').replace(EXPORT_LIST, '').replace(EXPORT_PREFIX, '');
    const leftover = body.match(/^\s*(?:import|export)\b.*$/m);
    if (leftover) throw new Error(`${name}: unsupported module syntax: ${leftover[0].trim()}`);
    for (const [, single, destructured] of body.matchAll(DECLARATION)) {
      const declared = single ? [single] : destructured.split(',').map(part => part.split(':').at(-1).split('=')[0].trim()).filter(Boolean);
      for (const declaredName of declared) {
        if (owners.has(declaredName)) throw new Error(`Top-level name "${declaredName}" is declared in both ${owners.get(declaredName)} and ${name}`);
        owners.set(declaredName, name);
      }
    }
    return `// ---- ${name}\n${body.trim()}\n`;
  });
  return `// Generated by scripts/build.mjs from ${entryName}. Do not edit; run \`npm run build\`.\n(() => {\n'use strict';\n\n${bodies.join('\n')}})();\n`;
}

export function buildTool(tool) {
  const entry = resolve(JS_DIR, tool, 'main.js');
  return bundle(readModules(entry), relative(ROOT, entry));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const tool of TOOLS) {
    writeFileSync(bundlePath(tool), buildTool(tool));
    console.log(`Wrote ${relative(ROOT, bundlePath(tool))}`);
  }
}
